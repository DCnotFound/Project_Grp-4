CREATE TABLE IF NOT EXISTS staging.hdb_resale (
    source_row_id BIGINT PRIMARY KEY,
    month DATE NOT NULL,
    town TEXT NOT NULL,
    flat_type TEXT NOT NULL,
    block TEXT NOT NULL,
    street_name TEXT NOT NULL,
    storey_range TEXT NOT NULL,
    floor_area_sqm NUMERIC(6, 1) NOT NULL,
    flat_model TEXT NOT NULL,
    lease_commence_date SMALLINT NOT NULL,
    remaining_lease TEXT NOT NULL,
    resale_price NUMERIC(12, 2) NOT NULL,
    storey_lower SMALLINT NOT NULL,
    storey_upper SMALLINT NOT NULL,
    storey_midpoint NUMERIC(4, 1) NOT NULL,
    remaining_lease_years SMALLINT NOT NULL,
    remaining_lease_extra_months SMALLINT NOT NULL,
    remaining_lease_months SMALLINT NOT NULL,
    address_key TEXT NOT NULL,
    possible_duplicate BOOLEAN NOT NULL,
    duplicate_group_size SMALLINT NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS staging.hdb_property (
    property_row_id BIGINT PRIMARY KEY,
    blk_no TEXT NOT NULL,
    street TEXT NOT NULL,
    max_floor_lvl SMALLINT NOT NULL,
    year_completed SMALLINT NOT NULL,
    residential BOOLEAN NOT NULL,
    commercial BOOLEAN NOT NULL,
    market_hawker BOOLEAN NOT NULL,
    miscellaneous BOOLEAN NOT NULL,
    multistorey_carpark BOOLEAN NOT NULL,
    precinct_pavilion BOOLEAN NOT NULL,
    bldg_contract_town TEXT NOT NULL,
    total_dwelling_units INTEGER NOT NULL,
    "1room_sold" INTEGER NOT NULL,
    "2room_sold" INTEGER NOT NULL,
    "3room_sold" INTEGER NOT NULL,
    "4room_sold" INTEGER NOT NULL,
    "5room_sold" INTEGER NOT NULL,
    exec_sold INTEGER NOT NULL,
    multigen_sold INTEGER NOT NULL,
    studio_apartment_sold INTEGER NOT NULL,
    "1room_rental" INTEGER NOT NULL,
    "2room_rental" INTEGER NOT NULL,
    "3room_rental" INTEGER NOT NULL,
    other_room_rental INTEGER NOT NULL,
    address_key TEXT NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS staging.load_audit (
    load_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    status TEXT NOT NULL CHECK (status IN ('STARTED', 'COMPLETED', 'FAILED')),
    resale_rows BIGINT,
    property_rows BIGINT,
    details JSONB
);
